    private void playAudio(String filePath) {
        try {
            File audioFile = new File(filePath);
            AudioInputStream audioStream = AudioSystem.getAudioInputStream(audioFile);
            clip = AudioSystem.getClip();
            clip.open(audioStream);
            clip.start();
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }
        private void stopAudio() { 
        if (clip != null && clip.isRunning()) {
            clip.stop();
        }
    }


    public void CollisionDetection(){
        Soul.addMouseMotionListener((MouseMotionListener) this);
        ImageIcon icon1 = new ImageIcon("/images/Soul.png");
        Soul = new JLabel(icon1);
        Soul.setBounds(50, 50, 30, 30);
        add(Soul);

        ImageIcon icon2 = new ImageIcon("/images/Bone.png");
        Bone = new JLabel(icon2);
        Bone.setBounds(200, 200, 30, 40);
        add(Bone);

        Timer timer = new Timer(10, (ActionListener) this); 
        timer.start();
    }

    public boolean collides() {
        Rectangle rect1 = Soul.getBounds();
        Rectangle rect2 = Bone.getBounds();
        return rect1.intersects(rect2);
    }

    private void initializeIconPosition() {
        int panelWidth = Border.getWidth();
        int panelHeight = Border.getHeight();

        int iconWidth = Bone.getPreferredSize().width;
        int iconHeight = Bone.getPreferredSize().height;

        int x = (panelWidth - iconWidth) / 2;
        int y = (panelHeight - iconHeight) / 2;

        Bone.setBounds(x, y, iconWidth, iconHeight);
    }

    private void moveIconRandomly() {
        int panelWidth = Border.getWidth();
        int panelHeight = Border.getHeight();

        int iconWidth = Bone.getWidth();
        int iconHeight = Bone.getHeight();

        Random random = new Random();
        int x = random.nextInt(panelWidth - iconWidth);
        int y = random.nextInt(panelHeight - iconHeight);

        Bone.setLocation(x, y);
    }

    private void startIconMovementTimer() {
        Timer timer = new Timer(1000, new ActionListener() {
            @Override
            public void actionPerformed(ActionEvent e) {
                moveIconRandomly();
            }
        });
        timer.start();
    }
        private void startDisappearTimer() {
        Timer disappearTimer = new Timer(10000, new ActionListener() {
            @Override
            public void actionPerformed(ActionEvent e) {
                Bone.setVisible(false);
                Soul.setVisible(false);
                fight.setEnabled(true);
                act.setEnabled(true);
                item.setEnabled(true);
                mercy.setEnabled(true);
                timer.stop();
            }
        });
    disappearTimer.setRepeats(false);
        disappearTimer.start();
    }
